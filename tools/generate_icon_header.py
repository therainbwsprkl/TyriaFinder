#!/usr/bin/env python3
"""Regenerate src/icon_data.h from assets/icon.png + assets/icon_hover.png.

The PNG bytes are embedded in the DLL as C arrays, so the addon needs no
external files at runtime. Re-run after editing the icons:
    python3 tools/generate_icon_header.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def emit(name, path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", f"{path} is not a PNG"
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return (f"// {os.path.basename(path)} ({len(data)} bytes, PNG)\n"
            f"static const unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"
            f"static const unsigned int {name}_SIZE = {len(data)};\n")

out = ("// Generated by tools/generate_icon_header.py -- do not edit by hand.\n"
       "// QuickAccess icon PNGs, embedded so the DLL needs no external files.\n"
       "#pragma once\n\n"
       + emit("kIconPng", os.path.join(ROOT, "assets", "icon.png")) + "\n"
       + emit("kIconHoverPng", os.path.join(ROOT, "assets", "icon_hover.png")))

with open(os.path.join(ROOT, "src", "icon_data.h"), "w") as f:
    f.write(out)
print(f"wrote src/icon_data.h")
