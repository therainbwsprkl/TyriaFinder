#!/usr/bin/env python3
"""Generate src/pois_data.h from data/pois.json.
Unnamed entries get a synthetic display label "Vista — <Map>" / "Waypoint — <Map>"
(see data/COVERAGE.md); the real API name (possibly null) is kept in `name`.
Curated keyword tags from data/tags.json (merged into pois.json by
tools/apply_tags.py) are emitted as a single '|' separated string in the
`tags` field ("" when an entry has none); see data/tags.json for sources.
"""
import json, os
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
data = json.load(open(os.path.join(BASE, "data", "pois.json")))
rows = data["entries"]
type_id = {"waypoint": 0, "landmark": 1, "vista": 2}
lines = []
lines.append("// Generated by tools/generate_pois_header.py from data/pois.json")
lines.append("// DO NOT EDIT BY HAND. Regenerate after rebuilding the dataset.")
lines.append(f"// {len(rows)} entries (2026-11-16, official GW2 API). See data/COVERAGE.md.")
tagged = sum(1 for r in rows if r.get("tags"))
phrases = sum(len(r.get("tags") or []) for r in rows)
lines.append(f"// {tagged} entries carry curated keyword tags (v1.7, data/tags.json, {phrases} phrases).")
lines.append("// continent: 1 = Tyria, 2 = Mists. The 32 entries with no continent")
lines.append("// in the API (map 1219, 'Enemy of My Enemy: The Beastmarshal', a")
lines.append("// Crystal Desert story instance) are emitted as 1 — their coords")
lines.append("// (x ~64-68k, y ~54-55k) sit inside the Tyria continent dims.")
lines.append("#pragma once")
lines.append("")
lines.append("struct PoiEntry { int id; const char* name; const char* display; int type; int map_id; const char* map_name; const char* region; float x; float y; const char* chat_link; const char* tags; int continent; };")
lines.append("enum PoiType { POI_WAYPOINT = 0, POI_LANDMARK = 1, POI_VISTA = 2 };")
lines.append(f"static const int kPoiCount = {len(rows)};")
lines.append("static const PoiEntry kPois[] = {")
for r in rows:
    name = r.get("name") or ""
    if name:
        display = name
    elif r["type"] == "vista":
        display = f"Vista - {r['map_name']}"
    else:
        display = f"Waypoint - {r['map_name']}"
    x, y = float(r["coord"][0]), float(r["coord"][1])
    tags = "|".join(r.get("tags") or [])
    continent = r.get("continent_id") or 1
    lines.append(f'    {{{r["id"]}, "{esc(name)}", "{esc(display)}", {type_id[r["type"]]}, {r["map_id"]}, "{esc(r["map_name"])}", "{esc(r["region"])}", {x!r}f, {y!r}f, "{esc(r["chat_link"])}", "{esc(tags)}", {continent}}},')
lines.append("};")
open(os.path.join(BASE, "src", "pois_data.h"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
tagged = sum(1 for r in rows if r.get("tags"))
print(f"wrote src/pois_data.h: {len(rows)} entries, {tagged} with tags")
